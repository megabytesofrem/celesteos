#!/usr/bin/env ruby

require "optparse"
require "fileutils"
require "pathname"

# BSD systemcalls are offset by 0x2000000, mirroring Darwin
SYS_BSD_OFFSET = 0x2000000

REGISTER_ARGUMENTS = %w[rdi rsi rdx r10 r8 r9].freeze
BANNER = "/* Generated by scripts/make_syscalls.rb. Do not edit. */"

# Regular expressions for parsing syscall master table entries and prototypes
SYSCALL_PATTERN = /
    \A\s*
    (?<number>-?\d+)\s+
    (?<type_flag>[A-Z_]+)
    (?<metadata>(?:\s+[A-Z_]+)*)
    \s*\{\s*
    (?<prototype>.*?)
    \s*\}\s*
    \z
/x
PROTOTYPE_PATTERN = /
    \A\s*
    (?<return_type>.*?)
    \s+
    (?<name>[A-Za-z_]\w*)
    \s*\(
    (?<arguments>.*)
    \)
    \s*;\s*\z
/x

# An include directive in a C source file
class IncludeDirective
    attr_reader :path

    def initialize(path)
        @path = path
    end

    def to_s(prefix = "")
        return "#include #{@path}" if prefix.empty?

        opener = @path[0]
        closer = @path[-1]
        path = @path[1...-1]
        prefixed_path = "#{prefix.sub(%r{/+\z}, "")}/#{path.sub(%r{\A/+}, "")}"
        "#include #{opener}#{prefixed_path}#{closer}"
    end
end

# An argument in a syscall prototype
class Argument
    attr_reader :c_type, :name

    def initialize(c_type, name)
        @c_type = c_type
        @name = name
    end

    def to_s
        "#{@c_type} #{@name}"
    end
end

# A syscall as defined in the master table
class Syscall
    attr_reader :number, :type_flag, :name, :return_type, :arguments, :returns_port

    def initialize(number, type_flag, name, return_type, arguments, returns_port)
        @number = number
        @type_flag = type_flag
        @name = name
        @return_type = return_type
        @arguments = arguments
        @returns_port = returns_port
    end

    def is_mach_call?
        @number < 0
    end

    def is_bsd_call?
        !is_mach_call?
    end

    def encoded_number
        return is_mach_call? ? @number : @number + SYS_BSD_OFFSET
    end

    def stack_count
        [@arguments.size - REGISTER_ARGUMENTS.length, 0].max
    end

    def table_index
        is_mach_call? ? -encoded_number : encoded_number - SYS_BSD_OFFSET
    end
end

def parse_declaration(declaration)
    
    # Parse a C declaration of the form "type *name" or "type name"
    match = /\A\s*(.*?)\s*(\*+\s*)?([A-Za-z_]\w*)\s*\z/.match(declaration)

    raise ArgumentError, "invalid C declaration: #{declaration.inspect}" unless match

    base_type = match[1].strip
    pointer = match[2].to_s.strip
    name = match[3]
    c_type = [base_type, pointer].reject(&:empty?).join(" ")
    c_type = "intptr_t" if c_type == "ssize_t"
    c_type = "intptr_t #{pointer}" if base_type == "ssize_t" && !pointer.empty?
    raise ArgumentError, "missing C type in declaration: #{declaration.inspect}" if c_type.empty?

    [c_type, name]
end

def split_arguments(arguments)
    return [] if arguments.strip.empty? || arguments.strip == "void"

    result = []
    start = 0
    paren_depth = 0
    bracket_depth = 0
    arguments.each_char.with_index do |character, index|
        # Match parentheses, brackets, and commas to correctly split arguments;
        # keep track of the depth of nested parentheses and brackets
        case character
        when "("
            paren_depth += 1
        when ")"
            paren_depth -= 1
        when "["
            bracket_depth += 1
        when "]"
            bracket_depth -= 1
        when ","
            if paren_depth.zero? && bracket_depth.zero?
                result << arguments[start...index].strip
                start = index + 1
            end
        end
        raise ArgumentError, "unbalanced C argument list: #{arguments.inspect}" if
            paren_depth.negative? || bracket_depth.negative?
    end
    unless paren_depth.zero? && bracket_depth.zero?
        raise ArgumentError, "unbalanced C argument list: #{arguments.inspect}"
    end
    result << arguments[start..].strip
    result
end

def parse_prototype(prototype)
    # Parse a syscall prototype of the form "return_type name(arguments);"
    match = PROTOTYPE_PATTERN.match(prototype)
    raise ArgumentError, "invalid syscall prototype: #{prototype.inspect}" unless match

    # Extract the return type, name, and arguments from the prototype match
    return_type = match[:return_type].strip
    name = match[:name]
    arguments = split_arguments(match[:arguments]).map do |declaration|
        c_type, argument_name = parse_declaration(declaration)
        Argument.new(c_type, argument_name)
    end
    return_type, return_pointer = parse_declaration("#{return_type} result")
    return_type = [return_type, return_pointer == "result" ? nil : return_pointer]
                 .compact.join(" ")

    # Return the name, return_type and arguments
    [name, return_type, arguments]
end

# Parse the master syscall table and return syscall objects and include directives
def parse_master_table(text)
    calls = []
    includes = []
    seen_numbers = {}

    text = text.gsub("\u00a0", " ").gsub(/\\\r?\n/, " ")
    text.each_line.with_index(1) do |line, line_number|
        stripped = line.strip
        next if stripped.empty? || stripped.start_with?(";", "//")

        # Process an include directive
        if (include_match = /\A#include\s+(<[^>\n]+>|"[^"\n]+")/.match(stripped))
            includes << IncludeDirective.new(include_match[1])
            next
        end

        # Skip preprocessor directives and comments
        next if stripped.start_with?("#")

        # Process a syscall entry
        match = SYSCALL_PATTERN.match(line)
        unless match
            if stripped.match?(/\A-?\d+\s/)
                raise ArgumentError, "malformed syscall entry on line #{line_number}"
            end
            next
        end

        # Extract the syscall number, type flag, and metadata from the match
        number = Integer(match[:number], 10)
        type_flag = match[:type_flag]
        metadata = match[:metadata].split
        unless %w[STD NOARGS UNIMPL OBSOL NODEF].include?(type_flag)
            raise ArgumentError, "unknown syscall type #{type_flag.inspect} on line #{line_number}"
        end
        unknown_metadata = metadata - %w[NOLOCK NO_INJECT COMPAT_43 RETURNS_PORT]
        unless unknown_metadata.empty?
            raise ArgumentError, "unknown syscall metadata #{unknown_metadata.join(', ')} on line #{line_number}"
        end
        next if %w[UNIMPL OBSOL].include?(type_flag)
        if seen_numbers.key?(number)
            raise ArgumentError, "duplicate syscall number #{number} on line #{line_number}"
        end

        # Record the syscall information and add it to the calls array
        name, return_type, arguments = parse_prototype(match[:prototype])
        calls << Syscall.new(
            number, type_flag, name, return_type, arguments,
            metadata.include?("RETURNS_PORT")
        )
        seen_numbers[number] = true
    end

    [calls.sort_by(&:number), includes]
end

# Generate the sys_enter.h header content for the given syscalls, includes, and prefix
def generate_header(calls, includes, prefix)
    lines = [
        BANNER,
        "#ifndef CELESTEOS_SYS_ENTER_H",
        "#define CELESTEOS_SYS_ENTER_H",
        "",
        '#include "sys_dispatch.h"'
    ]

    # Convert each include directive to a string with the given prefix
    includes.each { |include| lines << include.to_s(prefix) }
    lines << ""

    calls.each do |call|
        if call.type_flag != "NOARGS"
            lines << "struct sys_#{call.name}_args {"
            if call.arguments.empty?
                lines << "    unsigned char unused;"
            else
                call.arguments.each { |argument| lines << "    #{argument};" }
            end
            lines.concat(["};", ""])
        end
        if call.number.positive?
            lines << "#{call.return_type} sys_#{call.name}(const struct sys_#{call.name}_args *args);"
            lines << ""
        end
    end

    # Build sys_enter.h
    lines.concat(["#endif /* CELESTEOS_SYS_ENTER_H */", ""])
    lines.join("\n")
end

# Return the count of Mach trap table entries
def mach_trap_table_count(calls)
    calls.select(&:is_mach_call?).map { |call| call.number.abs }.max.to_i + 1
end

# Return the count of BSD syscall table entries
def bsd_syscall_table_count(calls)
    calls.select(&:is_bsd_call?).map(&:number).max.to_i + 1
end

# Generate the sys_dispatch.h header content for the given syscalls
def generate_dispatch_header(calls)
    # Determine the maximum stack size required for syscall arguments and build
    # sys_dispatch.h header content
    max_stack = [calls.map(&:stack_count).max.to_i, 1].max
    [
        BANNER,
        "#ifndef CELESTEOS_SYS_DISPATCH_H",
        "#define CELESTEOS_SYS_DISPATCH_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        "#include <kernel/stack_frame.h>",
        "",
        "#define SYS_BSD_OFFSET INT64_C(0x2000000)",
        "#define MACH_TRAP_TABLE_COUNT #{mach_trap_table_count(calls)}u",
        "#define BSD_SYSCALL_TABLE_COUNT #{bsd_syscall_table_count(calls)}u",
        "#define SYS_MAX_STACK_ARGS #{max_stack}u",
        "",
        "typedef int64_t (*sys_handler_t)(const stack_frame_t *frame,",
        "                                 const uint64_t *stack_args);",
        "",
        "typedef struct syscall_table_entry {",
        "    const char *name;",
        "    size_t argument_count;",
        "    bool returns_port;",
        "    sys_handler_t handler;",
        "} syscall_table_entry_t;",
        "",
        "#define MACH_TRAP(trap_name, argc, port_result, function) \\",
        "    { #trap_name, (argc), (port_result), (function) }",
        "#define MACH_TRAP_INVALID { NULL, 0, false, NULL }",
        "#define BSD_SYSCALL(call_name, argc, function) \\",
        "    { #call_name, (argc), false, (function) }",
        "#define BSD_SYSCALL_INVALID { NULL, 0, false, NULL }",
        "",
        "extern const syscall_table_entry_t mach_trap_table[MACH_TRAP_TABLE_COUNT];",
        "extern const syscall_table_entry_t bsd_syscall_table[BSD_SYSCALL_TABLE_COUNT];",
        "",
        "const syscall_table_entry_t *syscall_entry_lookup(int64_t number);",
        "int64_t sys_dispatch(int64_t number, const stack_frame_t *frame);",
        "const char *syscall_name(int64_t number);",
        "",
        "#endif /* CELESTEOS_SYS_DISPATCH_H */",
        ""
    ].join("\n")
end

# Generate the sys_dispatch.c source file content for the given syscalls
def generate_dispatch(calls)
    lines = [
        BANNER,
        '#include "sys_enter.h"',
        "#include <kernel/memory/pmap.h>",
        "#include <libkernel.h>",
        ""
    ]

    # Declare external references for BSD syscalls
    calls.each do |call|
        next unless call.is_bsd_call?

        lines << "extern #{call.return_type} sys_#{call.name}("
        lines[-1] += "const struct sys_#{call.name}_args *args) __attribute__((weak));"
    end
    lines << ""

    # Generate dispatch functions for each syscall
    calls.each do |call|
        lines.concat([
            "static int64_t dispatch_#{call.name}(const stack_frame_t *frame,",
            "                                 const uint64_t *stack_args) {"
        ])
        if call.is_bsd_call?
            lines.concat([
                "    if (sys_#{call.name} == NULL) {",
                "        klog(KLOG_WARN, \"sys_dispatch: unimplemented BSD syscall: #{call.name}\\n\");",
                "        return -1;",
                "    }"
            ])
        end
        lines << "    (void)frame;" if call.arguments.empty?
        lines << "    (void)stack_args;" if call.stack_count.zero?
        if !call.arguments.empty? || call.is_bsd_call?
            lines << "    const struct sys_#{call.name}_args args = {"
            call.arguments.each_with_index do |argument, index|
                source = if index < REGISTER_ARGUMENTS.length
                           "frame->#{REGISTER_ARGUMENTS[index]}"
                         else
                           "stack_args[#{index - REGISTER_ARGUMENTS.length}]"
                         end
                lines << "        .#{argument.name} = (#{argument.c_type})#{source},"
            end
            lines << "        .unused = 0," if call.arguments.empty?
            lines << "    };"
        end

        # Generate the invocation of the syscall with the prepared arguments
        # Mach calls are invoked directly by name, while BSD calls use the sys_ prefix and take a pointer to the args structure
        invocation = if call.is_mach_call?
                       "#{call.name}(#{call.arguments.map { |argument| "args.#{argument.name}" }.join(", ")})"
                     else
                       "sys_#{call.name}(&args)"
                     end
        if call.return_type == "void"
            lines.concat(["    #{invocation};", "    return 0;"])
        else
            lines << "    return (int64_t)#{invocation};"
        end
        lines.concat(["}", ""])
    end

    # Build both system call tables: Mach trap table and BSD syscall table
    mach_calls = calls.select(&:is_mach_call?).to_h { |call| [call.table_index, call] }
    bsd_calls = calls.select(&:is_bsd_call?).to_h { |call| [call.table_index, call] }

    # Generate the Mach trap table entries
    lines << "const syscall_table_entry_t mach_trap_table[MACH_TRAP_TABLE_COUNT] = {"
    mach_trap_table_count(calls).times do |index|
        call = mach_calls[index]
        if call
            port_result = call.returns_port ? "true" : "false"
            lines << "    /* #{format('%2d', index)} */ MACH_TRAP(#{call.name}, #{call.arguments.length}, #{port_result}, dispatch_#{call.name}),"
        else
            lines << "    /* #{format('%2d', index)} */ MACH_TRAP_INVALID,"
        end
    end

    # Generate the BSD syscall table entries
    lines.concat(["};", "", "const syscall_table_entry_t bsd_syscall_table[BSD_SYSCALL_TABLE_COUNT] = {"])
    bsd_syscall_table_count(calls).times do |index|
        call = bsd_calls[index]
        if call
            lines << "    /* #{format('%2d', index)} */ BSD_SYSCALL(#{call.name}, #{call.arguments.length}, dispatch_#{call.name}),"
        else
            lines << "    /* #{format('%2d', index)} */ BSD_SYSCALL_INVALID,"
        end
    end

    lines.concat([
        "};",
        "",
        "const syscall_table_entry_t *syscall_entry_lookup(int64_t number) {",
        "    if (number < 0) {",
        "        uint64_t trap_index = (uint64_t)(-(number + 1)) + 1;",
        "        return trap_index < MACH_TRAP_TABLE_COUNT ? &mach_trap_table[trap_index] : NULL;",
        "    }",
        "    if (number >= SYS_BSD_OFFSET) {",
        "        uint64_t syscall_index = (uint64_t)(number - SYS_BSD_OFFSET);",
        "        return syscall_index < BSD_SYSCALL_TABLE_COUNT",
        "                   ? &bsd_syscall_table[syscall_index]",
        "                   : NULL;",
        "    }",
        "    return NULL;",
        "}",
        "",
        "int64_t sys_dispatch(int64_t number, const stack_frame_t *frame) {",
        "    const syscall_table_entry_t *entry = syscall_entry_lookup(number);",
        "    if (entry == NULL || entry->handler == NULL) {",
        "        if (number < 0) {",
        '            klog(KLOG_WARN, "sys_dispatch: unhandled Mach trap: %d\\n", (int)number);',
        "        } else {",
        '            klog(KLOG_WARN, "sys_dispatch: unhandled BSD syscall: 0x%x\\n", (unsigned int)number);',
        "        }",
        "        return -1;",
        "    }",
        "    size_t needed = entry->argument_count > 6 ? entry->argument_count - 6 : 0;",
        "    if (frame == NULL) {",
        '        klog(KLOG_ERROR, "sys_dispatch: missing frame for %s\\n", entry->name);',
        "        return -1;",
        "    }",
        "    uint64_t stack_args[SYS_MAX_STACK_ARGS] = {0};",
        "    if (needed != 0 &&",
        "        (frame->rsp > UINT64_MAX - sizeof(uint64_t) ||",
        "         pmap_copy_from_user(stack_args, frame->rsp + sizeof(uint64_t),",
        "                             needed * sizeof(uint64_t)) != 0)) {",
        '        klog(KLOG_WARN, "sys_dispatch: invalid user stack for %s\\n", entry->name);',
        "        return -1;",
        "    }",
        "    return entry->handler(frame, stack_args);",
        "}",
        ""
    ])
    lines.join("\n")
end

def generate_names
    [
        BANNER,
        '#include "sys_dispatch.h"',
        "",
        "const char *syscall_name(int64_t number) {",
        "    const syscall_table_entry_t *entry = syscall_entry_lookup(number);",
        '    return entry != NULL && entry->handler != NULL ? entry->name : "unknown";',
        "}",
        ""
    ].join("\n")
end

def main
    options = {
        output_dir: Pathname.new(__dir__).join("../kernel").cleanpath,
        include_prefix: ""
    }
    parser = OptionParser.new do |opts|
        opts.banner = "Usage: ruby scripts/make_syscalls.rb TABLE [options]"
        opts.on("--output-dir DIR", "Generated file directory") do |directory|
            options[:output_dir] = Pathname.new(directory)
        end
        opts.on("--include-prefix PREFIX", "Prefix for included headers") do |prefix|
            options[:include_prefix] = prefix
        end
    end

    begin
        arguments = parser.parse(ARGV)
        if arguments.length != 1
            warn parser
            return 2
        end

        calls, includes = parse_master_table(File.read(arguments[0], encoding: "UTF-8"))
        outputs = {
            "sys_enter.h" => generate_header(calls, includes, options[:include_prefix]),
            "sys_dispatch.h" => generate_dispatch_header(calls),
            "sys_dispatch.c" => generate_dispatch(calls),
            "sys_names.c" => generate_names
        }
        FileUtils.mkdir_p(options[:output_dir])
        outputs.each do |filename, contents|
            File.write(options[:output_dir].join(filename), contents)
        end
    rescue OptionParser::ParseError, ArgumentError, Errno::ENOENT => error
        warn "#{File.basename($PROGRAM_NAME)}: #{error.message}"
        return 1
    end
    0
end

exit main if $PROGRAM_NAME == __FILE__