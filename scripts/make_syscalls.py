#!/usr/bin/env python3
"""Generate kernel syscall interfaces from an OpenBSD/XNU master table using Lark.

Usage: scripts/make_syscalls.py src/kernel/syscalls.master [--output-dir src/kernel] [--include-prefix kernel/bsd/]
"""

import argparse
from dataclasses import dataclass
from pathlib import Path
import sys

from lark import Lark, Transformer, v_args

# --- Grammar Definition ---
SYSCALL_GRAMMAR = r"""
    start: (line_continuation | comment_line | include_directive | directive | entry)*

    entry: NUMBER TYPE_FLAG [MODIFIER*] "{" prototype "}"
    
    include_directive: INCLUDE_DIRECTIVE
    directive: DIRECTIVE

    prototype: type_and_name "(" arg_list ")" ";"

    type_and_name: (CONST | STRUCT | ENUM | UNION | IDENTIFIER | STAR | "...")+
    
    arg_list: "void" -> empty_args
            | argument ("," argument)*

    argument: type_and_name

    TYPE_FLAG: "STD" | "NOARGS" | "UNIMPL" | "OBSOL" | "NODEF"
    MODIFIER: "NOLOCK" | "NO_INJECT" | "COMPAT_43"

    CONST: "const"
    STRUCT: "struct"
    ENUM: "enum"
    UNION: "union"
    STAR: "*"

    INCLUDE_DIRECTIVE: /#include\s+(<[^>\n]+>|"[^"\n]+")\s*/
    DIRECTIVE: /#[^\n]+/
    
    comment_line: /[ \t]*;[^\n]*/ | /[ \t]*\/\/[^\n]*/

    line_continuation: /[^\n]*\\\n/

    NUMBER: /-?\d+/
    IDENTIFIER: /[A-Za-z_][A-Za-z_0-9]*/

    %import common.WS
    %ignore WS
"""

BSD_OFFSET = 0x2000000
REGISTERS = ("rdi", "rsi", "rdx", "r10", "r8", "r9")
BANNER = "/* Generated by scripts/make_syscalls.py (Lark). Do not edit. */\n"


@dataclass(frozen=True)
class IncludeDirective:
    path: str


@dataclass(frozen=True)
class Argument:
    c_type: str
    name: str

    def declaration(self) -> str:
        return f"{self.c_type} {self.name}"


@dataclass(frozen=True)
class Syscall:
    number: int
    type_flag: str
    name: str
    return_type: str
    arguments: tuple[Argument, ...]

    @property
    def encoded_number(self) -> int:
        return self.number if self.number < 0 else BSD_OFFSET + self.number

    @property
    def stack_count(self) -> int:
        return max(0, len(self.arguments) - len(REGISTERS))


def format_c_type_and_name(tokens: list[str]) -> tuple[str, str]:
    """Extracts (c_type, name) cleanly from a list of declaration tokens.

    Example:
        ['mach_msg_header_t', '*', 'msg'] -> ('mach_msg_header_t *', 'msg')
        ['const', 'void', '*', 'buf']     -> ('const void *', 'buf')
    """
    if not tokens:
        raise ValueError("Empty token list for type/name declaration")

    name = tokens[-1]
    type_tokens = tokens[:-1]

    # Handle case where leading asterisks were stuck to the parameter name (*msg)
    while name.startswith("*"):
        type_tokens.append("*")
        name = name[1:].strip()

    base_parts = []
    pointer_stars = []

    for tok in type_tokens:
        tok_str = str(tok).strip()
        if tok_str == "*":
            pointer_stars.append("*")
        elif tok_str.endswith("*"):
            clean_tok = tok_str.rstrip("*").strip()
            stars = "*" * (len(tok_str) - len(clean_tok))
            if clean_tok:
                base_parts.append(clean_tok)
            pointer_stars.append(stars)
        else:
            base_parts.append(tok_str)

    base_type = " ".join(base_parts)
    if base_type == "ssize_t":
        base_type = "intptr_t"

    if pointer_stars:
        c_type = f"{base_type} {''.join(pointer_stars)}"
    else:
        c_type = base_type

    return c_type, name


def format_include_path(raw_path: str, prefix: str) -> str:
    if not prefix:
        return raw_path
    delim_start, delim_end = raw_path[0], raw_path[-1]
    inner_path = raw_path[1:-1]
    clean_prefix = prefix.rstrip("/") + "/"
    return f"{delim_start}{clean_prefix}{inner_path.lstrip('/')}{delim_end}"


@v_args(inline=True)
class SyscallTransformer(Transformer):
    def NUMBER(self, token):
        return int(token.value)

    def TYPE_FLAG(self, token):
        return str(token.value)

    def IDENTIFIER(self, token):
        return str(token.value)

    def STAR(self, token):
        return "*"

    def INCLUDE_DIRECTIVE(self, token):
        val = str(token.value).strip()
        path = val.split(None, 1)[1]
        return IncludeDirective(path=path)

    def include_directive(self, inc):
        return inc

    def directive(self, token):
        return None

    def comment_line(self, token=None):
        return None

    def type_and_name(self, *tokens):
        return [t.value if hasattr(t, "value") else str(t) for t in tokens]

    def argument(self, decl_tokens):
        c_type, name = format_c_type_and_name(decl_tokens)
        return Argument(c_type=c_type, name=name)

    def empty_args(self):
        return []

    def arg_list(self, *args):
        return list(args)

    def prototype(self, decl_tokens, args):
        ret_type, name = format_c_type_and_name(decl_tokens)
        return {"return_type": ret_type, "name": name, "args": tuple(args)}

    def entry(self, number, type_flag, *rest):
        proto = rest[-1]
        return Syscall(
            number=number,
            type_flag=type_flag,
            name=proto["name"],
            return_type=proto["return_type"],
            arguments=proto["args"],
        )

    def start(self, *items):
        return [item for item in items if isinstance(item, (Syscall, IncludeDirective))]


def parse_master_table(text: str) -> tuple[list[Syscall], list[IncludeDirective]]:
    text = text.replace("\xa0", " ")
    text = text.replace("\\\n", " ")

    parser = Lark(SYSCALL_GRAMMAR, parser="lalr", transformer=SyscallTransformer())
    parsed_items = parser.parse(text)

    calls: list[Syscall] = []
    includes: list[IncludeDirective] = []
    seen_numbers: set[int] = set()

    for item in parsed_items:
        if isinstance(item, IncludeDirective):
            includes.append(item)
        elif isinstance(item, Syscall):
            if item.type_flag in ("UNIMPL", "OBSOL"):
                continue
            if item.number in seen_numbers:
                raise ValueError(f"Duplicate syscall number in table: {item.number}")
            seen_numbers.add(item.number)
            calls.append(item)

    return sorted(calls, key=lambda c: c.number), includes


def number_literal(call: Syscall) -> str:
    return str(call.number) if call.number < 0 else f"0x{call.encoded_number:x}"


def generate_header(calls: list[Syscall], includes: list[IncludeDirective], prefix: str) -> str:
    lines = [
        BANNER.rstrip(),
        "#ifndef CELESTEOS_SYS_ENTER_H",
        "#define CELESTEOS_SYS_ENTER_H",
        "",
        '#include "sys_dispatch.h"',
    ]

    # Output header includes directly into sys_enter.h where arguments are declared
    if includes:
        for inc in includes:
            formatted_path = format_include_path(inc.path, prefix)
            lines.append(f"#include {formatted_path}")

    lines.append("")

    for call in calls:
        if call.type_flag != "NOARGS":
            lines.append(f"struct sys_{call.name}_args {{")
            if call.arguments:
                lines.extend(f"    {arg.declaration()};" for arg in call.arguments)
            else:
                lines.append("    unsigned char unused;")
            lines.extend(["};", ""])

        if call.number > 0:
            lines.extend([
                f"{call.return_type} sys_{call.name}(const struct sys_{call.name}_args *args);",
                "",
            ])

    lines.extend(["#endif /* CELESTEOS_SYS_ENTER_H */", ""])
    return "\n".join(lines)


def generate_dispatch_header() -> str:
    return "\n".join([
        BANNER.rstrip(),
        "#ifndef CELESTEOS_SYS_DISPATCH_H",
        "#define CELESTEOS_SYS_DISPATCH_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <kernel/stack_frame.h>",
        "",
        "#define SYS_BSD_OFFSET INT64_C(0x2000000)",
        "",
        "typedef int64_t (*sys_handler_t)(const stack_frame_t *frame,",
        "                                 const uint64_t *stack_args);",
        "",
        "typedef struct sys_dispatch_entry {",
        "    int64_t number;",
        "    size_t argument_count;",
        "    sys_handler_t handler;",
        "} sys_dispatch_entry_t;",
        "",
        "extern const sys_dispatch_entry_t sys_dispatch_table[];",
        "extern const size_t sys_dispatch_count;",
        "",
        "int64_t sys_dispatch(int64_t number, const stack_frame_t *frame);",
        "const char *syscall_name(int64_t number);",
        "",
        "#endif /* CELESTEOS_SYS_DISPATCH_H */",
        "",
    ])


def generate_dispatch(calls: list[Syscall]) -> str:
    lines = [
        BANNER.rstrip(),
        '#include "sys_enter.h"',
        "#include <kernel/memory/pmap.h>",
        "#include <libkernel.h>",
        "",
    ]

    for call in calls:
        if call.number > 0:
            lines.append(
                f"extern {call.return_type} sys_{call.name}("
                f"const struct sys_{call.name}_args *args) __attribute__((weak));"
            )

    lines.append("")

    for call in calls:
        lines.extend([
            f"static int64_t dispatch_{call.name}(const stack_frame_t *frame,",
            "                                 const uint64_t *stack_args) {",
        ])

        if call.number > 0:
            lines.extend([
                f"    if (sys_{call.name} == NULL) {{",
                f'        klog(KLOG_WARN, "sys_dispatch: unimplemented BSD syscall: {call.name}\\n");',
                "        return -1;",
                "    }",
            ])

        if not call.arguments:
            lines.append("    (void)frame;")
        if not call.stack_count:
            lines.append("    (void)stack_args;")

        if call.arguments or call.number > 0:
            lines.append(f"    const struct sys_{call.name}_args args = {{")
            for index, arg in enumerate(call.arguments):
                source = (
                    f"frame->{REGISTERS[index]}"
                    if index < len(REGISTERS)
                    else f"stack_args[{index - len(REGISTERS)}]"
                )
                lines.append(f"        .{arg.name} = ({arg.c_type}){source},")
            if not call.arguments:
                lines.append("        .unused = 0,")
            lines.append("    };")

        if call.number < 0:
            invocation = f"{call.name}({', '.join(f'args.{arg.name}' for arg in call.arguments)})"
        else:
            invocation = f"sys_{call.name}(&args)"

        if call.return_type == "void":
            lines.extend([f"    {invocation};", "    return 0;"])
        else:
            lines.append(f"    return (int64_t){invocation};")

        lines.extend(["}", ""])

    max_stack = max([c.stack_count for c in calls] or [0])

    lines.append("const sys_dispatch_entry_t sys_dispatch_table[] = {")
    for call in calls:
        lines.append(
            f"    {{ {number_literal(call)}, {len(call.arguments)}, dispatch_{call.name} }},"
        )
    lines.extend([
        "};",
        "const size_t sys_dispatch_count = sizeof(sys_dispatch_table) / sizeof(sys_dispatch_table[0]);",
        "",
        "int64_t sys_dispatch(int64_t number, const stack_frame_t *frame) {",
        "    for (size_t i = 0; i < sys_dispatch_count; ++i) {",
        "        const sys_dispatch_entry_t *entry = &sys_dispatch_table[i];",
        "        if (entry->number != number) {",
        "            continue;",
        "        }",
        "        size_t needed = entry->argument_count > 6 ? entry->argument_count - 6 : 0;",
        "        if (frame == NULL) {",
        '            klog(KLOG_ERROR, "sys_dispatch: missing frame for %s\\n", syscall_name(number));',
        "            return -1;",
        "        }",
        f"        uint64_t stack_args[{max(1, max_stack)}] = {{0}};",
        "        if (needed != 0 &&",
        "            (frame->rsp > UINT64_MAX - sizeof(uint64_t) ||",
        "             pmap_copy_from_user(stack_args, frame->rsp + sizeof(uint64_t),",
        "                                 needed * sizeof(uint64_t)) != 0)) {",
        '            klog(KLOG_WARN, "sys_dispatch: invalid user stack for %s\\n", syscall_name(number));',
        "            return -1;",
        "        }",
        "        return entry->handler(frame, stack_args);",
        "    }",
        "    if (number < 0) {",
        '        klog(KLOG_WARN, "sys_dispatch: Unhandled Mach trap: %d\\n", (int)number);',
        "    } else {",
        '        klog(KLOG_WARN, "sys_dispatch: Unhandled BSD syscall: 0x%x\\n", (unsigned int)number);',
        "    }",
        "    return -1;",
        "}",
        "",
    ])
    return "\n".join(lines)


def generate_names(calls: list[Syscall]) -> str:
    lines = [
        BANNER.rstrip(),
        '#include "sys_dispatch.h"',
        "",
        "const char *syscall_name(int64_t number) {",
        "    switch (number) {",
    ]
    for call in calls:
        lines.extend([f"    case {number_literal(call)}:", f'        return "{call.name}";'])
    lines.extend(['    default:', '        return "unknown";', "    }", "}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("table", type=Path, help="OpenBSD/XNU syscall definition master file")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "src/kernel",
        help="generated file directory (default: repository src/kernel)",
    )
    parser.add_argument(
        "--include-prefix",
        type=str,
        default="",
        help="Optional path prefix to prepend to #include directives (e.g., 'kernel/bsd/')",
    )
    options = parser.parse_args()
    try:
        calls, includes = parse_master_table(options.table.read_text(encoding="utf-8"))
        outputs = {
            "sys_enter.h": generate_header(calls, includes, options.include_prefix),
            "sys_dispatch.h": generate_dispatch_header(),
            "sys_dispatch.c": generate_dispatch(calls),
            "sys_names.c": generate_names(calls),
        }
        options.output_dir.mkdir(parents=True, exist_ok=True)
        for name, contents in outputs.items():
            (options.output_dir / name).write_text(contents, encoding="utf-8")
    except Exception as error:
        print(f"{parser.prog}: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())